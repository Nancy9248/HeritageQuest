/**
 * Retrieves the localized intro exchange for a monument.
 * Checks requested language, falls back to Hindi for Indian locales, or English as universal base.
 */
export function getLocalizedDuoIntro(monumentId, lang = 'en') {
  const mon = MULTILINGUAL_DUO_DIALOGUES[monumentId];
  if (!mon) return null;
  if (mon[lang]?.introExchange) return mon[lang].introExchange;
  if (['hi', 'mr', 'gu', 'bn', 'pa', 'or', 'ta', 'te', 'kn', 'ml'].includes(lang) && mon.hi?.introExchange) {
    return mon.hi.introExchange;
  }
  return mon.en?.introExchange || null;
}

/**
 * Retrieves localized dialogue exchanges for a monument.
 */
export function getLocalizedDuoDialogues(monumentId, lang = 'en') {
  const mon = MULTILINGUAL_DUO_DIALOGUES[monumentId];
  if (!mon) return [];
  if (mon[lang]?.dialogueExchanges) return mon[lang].dialogueExchanges;
  if (['hi', 'mr', 'gu', 'bn', 'pa', 'or', 'ta', 'te', 'kn', 'ml'].includes(lang) && mon.hi?.dialogueExchanges) {
    return mon.hi.dialogueExchanges;
  }
  return mon.en?.dialogueExchanges || [];
}
