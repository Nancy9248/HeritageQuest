export function getLocalizedHostDialogues(monumentId, lang = 'en') {
  const monumentDialogues = HOST_DIALOGUES[monumentId] || HOST_DIALOGUES['taj-mahal'];
  // If exact language exists, return it
  if (monumentDialogues[lang] && monumentDialogues[lang].length > 0) {
    return monumentDialogues[lang];
  }
  // Fallback to Hindi for Indian languages if available, else English
  const indianLangs = ['hi', 'mr', 'gu', 'bn', 'ta', 'te', 'kn', 'ml', 'pa', 'or'];
  if (indianLangs.includes(lang) && monumentDialogues['hi']) {
    return monumentDialogues['hi'];
  }
  return monumentDialogues['en'] || [];
}
